#!/usr/bin/env python3
"""Generate the Letters, numbers & symbols outline data from Roboto Bold.

ADR new-primitives-polyhedra-text §2.2, Phase A.3. Writes:

  web/glyphs.mjs         full outlines (worker / OCCT side only)
  web/glyph-metrics.mjs  bbox per glyph (UI-safe, small; main.js needs no advances)

Pipeline: pinned Roboto[wdth,wght].ttf (sha256-checked) -> static instance
wght 700 / wdth 100 with overlaps REMOVED (fontTools.varLib.instancer,
OverlapMode.REMOVE, needs skia-pathops) -> decompose components -> split
implied-on-curve TrueType quads into explicit quadratic segments -> drop
zero-length segments -> emit integers.

Coordinates are stored in HALF font units (font upm 2048 -> data upm 4096) so
the implied on-curve midpoints stay exact integers.

Usage:
  python3 -m venv .venv && .venv/bin/pip install -r tools/glyphs/requirements.txt
  .venv/bin/python tools/glyphs/extract.py            # write web/*.mjs
  .venv/bin/python tools/glyphs/extract.py --check    # exit 1 if stale
  --font PATH uses a local copy (still sha256-checked).
"""
import argparse
import hashlib
import json
import os
import sys
import urllib.request

FONT_URL = ("https://raw.githubusercontent.com/google/fonts/"
            "1c627bfa375fc51cf86fabeca4f6e08a95f0aa5c/ofl/roboto/Roboto%5Bwdth%2Cwght%5D.ttf")
FONT_SHA256 = "d7598e12c5dbef095ff8272cfc55da0250bd07fbdecbac8a530b9b277872a134"
FONT_VERSION = "Version 3.015"
OFL_URL = ("https://raw.githubusercontent.com/google/fonts/"
           "1c627bfa375fc51cf86fabeca4f6e08a95f0aa5c/ofl/roboto/OFL.txt")
OFL_SHA256 = "061402327a96aadb0bfb694a960ed289ecd38d383e396243831ab81feb109c41"
FONTTOOLS_VERSION = "4.65.0"
PATHOPS_VERSION = "0.9.2"
FONT_ID = "roboto-bold@1"
AXES = {"wght": 700, "wdth": 100}
SCALE = 2  # half font units

DIGITS = "0123456789"
UPPER = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
LOWER = "abcdefghijklmnopqrstuvwxyz"
SYMBOLS = "!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~"
CHARS = DIGITS + UPPER + LOWER + SYMBOLS
assert len(CHARS) == 94 and len(set(CHARS)) == 94

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
CACHE = os.path.join(HERE, ".cache")

HEADER = """// GENERATED by tools/glyphs/extract.py from Roboto Bold. Do not edit; see tools/glyphs/README.md.
// Copyright 2011 The Roboto Project Authors (https://github.com/googlefonts/roboto-classic)
// This Font Software is licensed under the SIL Open Font License, Version 1.1 (no Reserved
// Font Name); the licence is in licenses/Roboto-OFL-1.1.txt and at https://openfontlicense.org
// This data is a Modified Version of the Font Software: a wght 700 / wdth 100 static instance
// of Roboto[wdth,wght].ttf {version}, overlaps removed, quadratic outlines re-encoded.
// Source: {url}
// sha256 {sha}
"""


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 16), b""):
            h.update(block)
    return h.hexdigest()


def fetch(url, digest, name, local=None):
    path = local or os.path.join(CACHE, name)
    if not os.path.exists(path):
        if local:
            sys.exit(f"missing {local}")
        os.makedirs(CACHE, exist_ok=True)
        tmp = path + ".part"
        urllib.request.urlretrieve(url, tmp)
        os.replace(tmp, path)
    got = sha256(path)
    if got != digest:
        sys.exit(f"{path}: sha256 {got} != pinned {digest}")
    return path


def check_versions():
    import fontTools
    import pathops
    bad = []
    if fontTools.version != FONTTOOLS_VERSION:
        bad.append(f"fonttools {fontTools.version} (need {FONTTOOLS_VERSION})")
    if pathops.__version__ != PATHOPS_VERSION:
        bad.append(f"skia-pathops {pathops.__version__} (need {PATHOPS_VERSION})")
    if bad:
        sys.exit("pinned tool versions required: " + ", ".join(bad))


def to_commands(recording):
    """RecordingPen value -> [['M',x,y],['L',x,y],['Q',cx,cy,x,y],['Z']] in half units."""
    out, start, cur = [], None, None

    def pt(p):
        return [int(round(p[0] * SCALE)), int(round(p[1] * SCALE))]

    for op, args in recording:
        if op == "moveTo":
            start = cur = pt(args[0])
            out.append(["M", *cur])
        elif op == "lineTo":
            p = pt(args[0])
            if p != cur:
                out.append(["L", *p])
                cur = p
        elif op == "qCurveTo":
            if args[-1] is None:
                raise ValueError("off-curve-only contour")
            pts = [pt(p) for p in args]  # exact: font units are ints, x2 keeps midpoints ints
            for i in range(len(pts) - 1):
                c = pts[i]
                end = pts[i + 1] if i == len(pts) - 2 else [(pts[i][0] + pts[i + 1][0]) // 2,
                                                             (pts[i][1] + pts[i + 1][1]) // 2]
                if (c == cur and end == cur):
                    continue
                if c == cur or c == end:  # degenerate quad == line
                    if end != cur:
                        out.append(["L", *end])
                else:
                    out.append(["Q", *c, *end])
                cur = end
        elif op == "curveTo":
            raise ValueError("cubic segment in a TrueType font")
        elif op in ("closePath", "endPath"):
            # an explicit line back to the start is implied by Z
            if out and out[-1][0] == "L" and out[-1][1:] == start:
                out.pop()
            out.append(["Z"])
            cur = start = None
        else:
            raise ValueError(op)
    return out


def bounds(cmds):
    """Tight bbox of lines + quadratic segments (half units, floor/ceil to ints)."""
    xs, ys = [], []
    cur = None
    for c in cmds:
        if c[0] == "M" or c[0] == "L":
            cur = c[1:3]
            xs.append(cur[0]); ys.append(cur[1])
        elif c[0] == "Q":
            p0, p1, p2 = cur, c[1:3], c[3:5]
            xs.append(p2[0]); ys.append(p2[1])
            for k, arr in ((0, xs), (1, ys)):
                den = p0[k] - 2 * p1[k] + p2[k]
                if den:
                    t = (p0[k] - p1[k]) / den
                    if 0 < t < 1:
                        arr.append((1 - t) ** 2 * p0[k] + 2 * (1 - t) * t * p1[k] + t * t * p2[k])
            cur = p2
    import math
    return [math.floor(min(xs)), math.floor(min(ys)), math.ceil(max(xs)), math.ceil(max(ys))]


def build(font_path):
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer
    from fontTools.pens.recordingPen import DecomposingRecordingPen

    font = TTFont(font_path)
    if not font["name"].getDebugName(5).startswith(FONT_VERSION):
        sys.exit("unexpected font version " + font["name"].getDebugName(5))
    inst = instancer.instantiateVariableFont(font, AXES, overlap=instancer.OverlapMode.REMOVE)
    gs, cmap = inst.getGlyphSet(), inst.getBestCmap()
    upm = inst["head"].unitsPerEm
    cap = inst["OS/2"].sCapHeight
    glyphs, metrics = {}, {}
    for ch in CHARS:
        name = cmap[ord(ch)]
        pen = DecomposingRecordingPen(gs)
        gs[name].draw(pen)
        cmds = to_commands(pen.value)
        if not cmds:
            raise ValueError(f"empty glyph {ch!r}")
        adv = inst["hmtx"][name][0] * SCALE
        bb = bounds(cmds)
        glyphs[ch] = {"adv": adv, "bbox": bb, "path": cmds}
        metrics[ch] = list(bb)
    h_top = glyphs["H"]["bbox"][3]
    if h_top != cap * SCALE:
        sys.exit(f"capHeight {cap} does not match H top {h_top / SCALE}")
    info = {"id": FONT_ID, "name": "Roboto Bold", "upm": upm * SCALE, "capHeight": cap * SCALE,
            "ascender": inst["hhea"].ascent * SCALE, "descender": inst["hhea"].descent * SCALE}
    return info, glyphs, metrics


def js_string(s):
    return json.dumps(s, ensure_ascii=True)


def encode(cmds):
    """Compact relative form: op letter (m l q z) + ints; every x,y pair is relative to the
    previously written pair (control points included); z does not move the cursor."""
    out, x, y = [], 0, 0
    for c in cmds:
        if c[0] == "Z":
            out.append("z")
            continue
        nums = []
        for i in range(1, len(c), 2):
            nums += [c[i] - x, c[i + 1] - y]
            x, y = c[i], c[i + 1]
        out.append(c[0].lower() + " ".join(str(n) for n in nums).replace(" -", "-"))
    return "".join(out)


DECODER = """const cache=new Map();
// Absolute outline of one character: [['M',x,y] | ['L',x,y] | ['Q',cx,cy,x,y] | ['Z']].
// Returns a fresh array (callers may scale it in place); unknown characters return null.
export function glyphPath(ch){
 const g=GLYPH_FONT.glyphs[ch];if(!g)return null;
 let cmds=cache.get(ch);
 if(!cmds){
  cmds=[];let x=0,y=0;
  for(const [,op,nums] of g[5].matchAll(/([mlqz])([^mlqz]*)/g)){
   if(op==='z'){cmds.push(['Z']);continue;}
   const v=nums.match(/-?\\d+/g).map(Number),abs=[];
   for(let i=0;i<v.length;i+=2){x+=v[i];y+=v[i+1];abs.push(x,y);}
   cmds.push([op.toUpperCase(),...abs]);
  }
  cache.set(ch,cmds);
 }
 return cmds.map(c=>c.slice());
}
// {adv, bbox:[xMin,yMin,xMax,yMax]} in data units, or null.
export function glyphInfo(ch){const g=GLYPH_FONT.glyphs[ch];return g?{adv:g[0],bbox:g.slice(1,5)}:null;}
"""


def render(info, glyphs, metrics):
    head = HEADER.format(version=FONT_VERSION, url=FONT_URL, sha=FONT_SHA256)
    meta = ",".join(f"{k}:{json.dumps(v)}" for k, v in info.items())
    full = [head.rstrip("\n"),
            "// glyphs[c] = [advance, xMin, yMin, xMax, yMax, path]; path is a compact relative string",
            "// decoded by glyphPath(c). Units: half font units (upm 4096), y up. Outer contours are",
            "// clockwise, counters counter-clockwise; overlaps are removed, so NonZero and EvenOdd fills",
            "// agree. Scale by size / capHeight for cap height = size mm.",
            "// Import only from worker / OCCT code (kernel.mjs, cad-solid.mjs), never from main.js.",
            f"export const GLYPH_CHARS={js_string(CHARS)};",
            f"export const GLYPH_FONT=Object.freeze({{{meta},glyphs:Object.freeze({{"]
    items = list(glyphs.items())
    for i, (ch, g) in enumerate(items):
        body = json.dumps([g["adv"], *g["bbox"], encode(g["path"])], separators=(",", ":"))
        full.append(f"{js_string(ch)}:{body}{',' if i < len(items) - 1 else ''}")
    full += ["})});", DECODER.rstrip("\n"), "export default GLYPH_FONT;", ""]
    small = [head.rstrip("\n"),
             "// UI-safe metrics only (no outlines): m[c] = [xMin, yMin, xMax, yMax] in the same",
             "// half font units as glyphs.mjs (upm 4096). Cap height = size mm at scale size / capHeight.",
             f"export const GLYPH_CHARS={js_string(CHARS)};",
             f"export const GLYPH_METRICS=Object.freeze({{{meta},m:Object.freeze({{"
             + ",".join(f"{js_string(c)}:{json.dumps(m, separators=(',', ':'))}" for c, m in metrics.items())
             + "})});", ""]
    return "\n".join(full), "\n".join(small)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", help="local Roboto[wdth,wght].ttf (sha256 still checked)")
    ap.add_argument("--check", action="store_true", help="fail if web/glyphs*.mjs are stale")
    args = ap.parse_args()
    check_versions()
    font = fetch(FONT_URL, FONT_SHA256, "Roboto[wdth,wght].ttf", args.font)
    full, small = render(*build(font))
    targets = {os.path.join(ROOT, "web", "glyphs.mjs"): full,
               os.path.join(ROOT, "web", "glyph-metrics.mjs"): small}
    if args.check:
        stale = [p for p, t in targets.items()
                 if not os.path.exists(p) or open(p, encoding="utf-8").read() != t]
        if stale:
            sys.exit("stale: " + ", ".join(os.path.relpath(p, ROOT) for p in stale))
        print("glyph data is up to date")
        return
    for p, t in targets.items():
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(t)
        print("wrote", os.path.relpath(p, ROOT), len(t.encode()), "bytes")


if __name__ == "__main__":
    main()
